#!/bin/sh
set -e

# Миграции гоняем на старте: релиз — это один образ, отдельного шага деплоя нет.
# При нескольких репликах вынести в init-контейнер, чтобы не гонялись параллельно.
if [ "${RUN_MIGRATIONS:-1}" = "1" ]; then
  echo "Применяю миграции..."
  python manage.py migrate --noinput
fi

# Каталог загрузок принадлежит тому, а не образу, и его владелец переживает
# пересборку. Если права разъехались (например, файлы занесли в том контейнера с хоста
# через `cp`), то загрузка фото и материалов молча падала бы 500-й ошибкой
# только в момент сохранения формы. Пусть лучше видно при старте.
MEDIA_DIR="${MEDIA_ROOT:-/app/media}"
if [ -d "$MEDIA_DIR" ] && ! [ -w "$MEDIA_DIR" ]; then
  echo "ВНИМАНИЕ: $MEDIA_DIR недоступен для записи пользователю $(id -un)." >&2
  echo "  Загрузка файлов через панель работать не будет. Поправить владельца:" >&2
  echo "  podman exec --user root <контейнер> chown -R app:app $MEDIA_DIR" >&2
fi

exec "$@"
