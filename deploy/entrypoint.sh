#!/bin/sh
set -e

# Миграции гоняем на старте: релиз — это один образ, отдельного шага деплоя нет.
# При нескольких репликах вынести в init-контейнер, чтобы не гонялись параллельно.
if [ "${RUN_MIGRATIONS:-1}" = "1" ]; then
  echo "Применяю миграции..."
  python manage.py migrate --noinput
fi

exec "$@"
